/**
 * One tab per group — the shape the sheet is actually kept in.
 *
 * Each tab drops the `Group` column: the sync takes the group from the tab
 * name. That exercises the real path, including the tab that opens with a
 * title row above the headers, which is what real spreadsheets look like.
 */
const HEADER = FAKE_ROWS[0];
const GROUP_COL = HEADER.indexOf("Group");

const withoutGroup = (row) => row.filter((_, i) => i !== GROUP_COL);

function tabFor(group, opts = {}) {
  const rows = FAKE_ROWS.slice(1)
    .filter((r) => r[GROUP_COL] === group)
    .map(withoutGroup);

  return {
    name: group,
    rows: opts.titleRow
      ? [[`${group} — payroll`], [], withoutGroup(HEADER), ...rows]
      : [withoutGroup(HEADER), ...rows],
  };
}

